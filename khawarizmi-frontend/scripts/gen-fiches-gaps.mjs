// ── Fusion idempotente ─────────────────────────────────────────────
const fiches = JSON.parse(fs.readFileSync(FICHES_PATH, "utf8"))
const map = JSON.parse(fs.readFileSync(MAP_PATH, "utf8"))
let created = 0

for (const g of FICHES_GAPS) {
  const id = `fiche-${g.source}-${g.chapitreSlug}`
  if (fiches.some((f) => f.id === id)) {
    console.log(`ℹ️  déjà présente : ${id}`)
    continue
  }
  fiches.push({
    id,
    fileKey: null,
    num: null,
    titre: g.titre,
    breadcrumb: g.breadcrumb,
    achkalia: g.achkalia,
    objectif: g.objectif,
    duree: g.duree,
    idees: g.idees,
    bac: g.bac,
    quiz: g.quiz,
    source: g.source,
  })
  const existing = map.find((m) => m.chapterSlug === g.chapitreSlug)
  if (existing) {
    if (!existing.ficheIds.includes(id)) existing.ficheIds.push(id)
  } else {
    map.push({ chapterSlug: g.chapitreSlug, chapterAr: g.titre, ficheIds: [id] })
  }
  created++
  console.log(`✅ créée + câblée : ${id} → ${g.chapitreSlug}`)
}

fs.writeFileSync(FICHES_PATH, JSON.stringify(fiches, null, 2) + "\n", "utf8")
fs.writeFileSync(MAP_PATH, JSON.stringify(map, null, 2) + "\n", "utf8")

const faibles = fiches.filter((f) => !f.objectif || !f.achkalia || f.idees.length < 3)
console.log(`\n📊 fiches : ${fiches.length} | créées ce run : ${created} | incomplètes : ${faibles.length}`)
console.log(`🗺️  paires chapitre→fiche : ${map.length} | chapitres couverts : ${new Set(map.map((m) => m.chapterSlug)).size}/55`)
