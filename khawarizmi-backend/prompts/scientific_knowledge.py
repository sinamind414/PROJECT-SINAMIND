_MAX_VOCAB = 15
_MAX_FACTS = 8
_MAX_ERRORS = 5


def get_relevant_knowledge(context: str) -> str:
    """Selectionne et formate les connaissances scientifiques pertinentes.

    Analyse le contexte (question, scenario) et retourne un bloc texte
    avec les unites les plus pertinentes (max 2 unites).
    """
    if not context:
        return ""

    context_lower = context.lower()
    matched_units: list[dict[str, Any]] = []
    scores: list[tuple[int, dict[str, Any]]] = []

    for unit in ALL_UNITS:
        keywords = _UNIT_KEYWORDS.get(unit["id"], [])
        score = sum(1 for kw in keywords if kw.lower() in context_lower)
        if score > 0:
            scores.append((score, unit))

    scores.sort(key=lambda x: x[0], reverse=True)
    matched_units = [unit for _, unit in scores[:2]]

    if not matched_units:
        return ""

    return _build_knowledge_block(matched_units)


def get_relevant_knowledge_raw(context: str, max_units: int = 2) -> list[dict[str, Any]]:
    """Retourne les dictionnaires d'unites pertinents (sans formatage)."""
    if not context:
        return []

    context_lower = context.lower()
    scores: list[tuple[int, dict[str, Any]]] = []

    for unit in ALL_UNITS:
        keywords = _UNIT_KEYWORDS.get(unit["id"], [])
        score = sum(1 for kw in keywords if kw.lower() in context_lower)
        if score > 0:
            scores.append((score, unit))

    scores.sort(key=lambda x: x[0], reverse=True)
    return [unit for _, unit in scores[:max_units]]


# ── Normalisation des identifiants d'unités ─────────────────────────────
# VERB_UNIT_MAP et PRACTICAL_EXAMPLES utilisent « unite5-energie » alors que
# ALL_UNITS utilise « unite5-energetique » (les deux orthographes sont
# verrouillées par des tests existants). Toute recherche dans ALL_UNITS
# passe par cette canonisation pour que les deux formes résolvent la même
# unité (bug corrigé 2026-08-20 : les erreurs/connaissances de l'unité 5
# étaient silencieusement absentes de la remédiation).
_UNIT_ID_ALIASES: dict[str, str] = {
    "unite5-energie": "unite5-energetique",
}


def _canonical_unit_id(unit_id: str) -> str:
    """Résout l'identifiant canonique d'une unité (alias → id ALL_UNITS)."""
    if not unit_id:
        return unit_id
    return _UNIT_ID_ALIASES.get(unit_id, unit_id)


def build_knowledge_block(unit_ids: list[str]) -> str:
    """Formate un bloc de connaissance pour les unités specifiees par leur id."""
    ids = {_canonical_unit_id(i) for i in unit_ids}
    units = [u for u in ALL_UNITS if u["id"] in ids]
    if not units:
        return ""
    return _build_knowledge_block(units)


def _build_knowledge_block(units: list[dict[str, Any]]) -> str:
    """Construit le bloc texte a injecter dans le prompt."""
    parts: list[str] = []

    for unit in units:
        lines: list[str] = []
        lines.append(f"### {unit['title_ar']}")
        lines.append("")

        # Vocabulaire
        vocab = unit.get("vocabulary", [])
        if vocab:
            lines.append("**المصطلحات العلمية الأساسية:**")
            for term in vocab[:_MAX_VOCAB]:
                lines.append(f"- {term}")
            lines.append("")

        # Faits
        facts = unit.get("facts", [])
        if facts:
            lines.append("**حقائق يجب التحقق منها:**")
            for fact in facts[:_MAX_FACTS]:
                lines.append(f"- {fact}")
            lines.append("")

        # Erreurs
        errors = unit.get("errors", [])
        if errors:
            lines.append("**⚠️ أخطاء شائعة يجب كشفها:**")
            for err in errors[:_MAX_ERRORS]:
                lines.append(f"- {err}")
            lines.append("")

        parts.append("\n".join(lines))

    return "\n".join(parts)


